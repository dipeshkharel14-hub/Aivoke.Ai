// Usage: node scripts/generate-seed.mjs path/to/index.html > supabase/seed.sql
// Reads the TOOLS and CATS arrays from the original index.html and emits idempotent SQL.
import fs from "node:fs";
import vm from "node:vm";

const src = fs.readFileSync(process.argv[2] ?? "index.html", "utf8");
const grab = (name) => {
  const m = src.match(new RegExp(`const ${name} = (\\[[\\s\\S]*?\\n\\]);`));
  if (!m) throw new Error(`Could not find ${name}`);
  return vm.runInNewContext(m[1]);
};
const TOOLS = grab("TOOLS");
const CATS = grab("CATS").filter((c) => c.id !== "All");

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const slugify = (s) =>
  s.toLowerCase().replace(/&/g, " and ").replace(/·/g, "").replace(/\./g, "")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const tagline = (d) => {
  const first = d.split(/(?<=[.!?])\s/)[0].replace(/\.$/, "");
  if (first.length <= 110) return first;
  const cut = first.slice(0, 107);
  return cut.slice(0, cut.lastIndexOf(" ")) + "...";
};

const catSlug = new Map(CATS.map((c) => [c.id, slugify(c.id)]));
const seen = new Set();
const problems = [];
for (const t of TOOLS) {
  if (!catSlug.has(t.cat)) problems.push(`Unknown category ${t.cat} for ${t.name}`);
  if (!t.url.startsWith("https://")) problems.push(`Non-https url: ${t.name}`);
  const s = slugify(t.name);
  if (seen.has(s)) problems.push(`Duplicate slug: ${s}`);
  seen.add(s);
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
console.error(`OK: ${TOOLS.length} tools, ${CATS.length} categories`);

const out = [];
out.push("-- GENERATED by scripts/generate-seed.mjs from index.html. Safe to re-run (upserts).");
out.push("begin;");
out.push("insert into public.categories (slug, name, icon, sort_order) values");
out.push(CATS.map((c, i) => `  (${q(slugify(c.id))}, ${q(c.id)}, ${q(c.icon)}, ${i + 1})`).join(",\n"));
out.push("on conflict (slug) do update set name = excluded.name, icon = excluded.icon, sort_order = excluded.sort_order;");
out.push("");
out.push("insert into public.tools (slug, name, tagline, description, url, tags, category_slug, is_trending, is_new, status) values");
out.push(TOOLS.map((t) =>
  `  (${q(slugify(t.name))}, ${q(t.name)}, ${q(tagline(t.desc))}, ${q(t.desc)}, ${q(t.url)}, ` +
  `array[${t.tags.map(q).join(", ")}]::text[], ${q(catSlug.get(t.cat))}, ${t.trending}, ${t.isNew}, 'published')`
).join(",\n"));
out.push(`on conflict (slug) do update set name = excluded.name, tagline = excluded.tagline,
  description = excluded.description, url = excluded.url, tags = excluded.tags,
  category_slug = excluded.category_slug, is_trending = excluded.is_trending, is_new = excluded.is_new;`);
out.push("commit;");
console.log(out.join("\n"));
